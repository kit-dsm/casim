"""Generate concrete CoSy nodes from resolved ware_ops_algos cards.

This follows the per-card module approach of ware_ops_pipes' generator. Run
``python -m casim.pipelines.subproblems.generate_configured_components`` after editing
the configured cards or their manifest.
"""

from __future__ import annotations

import re
import inspect
from pathlib import Path

import ware_ops_algos.algorithms as algorithms
from ware_ops_algos.algorithms.algorithm_cards import load_packaged_algo_cards
from ware_ops_algos.algorithms.routing.routing import Routing


OUTPUT_DIR = Path(__file__).parent / "generated"
BASES = {"IncumbentStartBatching", "OrderCountWaiting"}


def _module_name(name: str) -> str:
    value = re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()
    value = re.sub(r"[^a-z0-9_]", "_", value)
    if not value or value[0].isdigit():
        raise ValueError(f"Invalid configured component name {name!r}")
    return value


def _render(name: str, implementation: dict) -> str:
    base = implementation["class_name"]
    header = "# Generated by casim.pipelines.subproblems.generate_configured_components. Do not edit.\n\n"
    if base == "OrderCountWaiting":
        minimum = int(implementation["min_orders"])
        return (header
                + "from casim.pipelines.subproblems.waiting import OrderCountWaitingNode\n\n\n"
                + f"class {name}(OrderCountWaitingNode):\n"
                + "    abstract = False\n"
                + f"    min_orders = {minimum}\n")
    if base == "IncumbentStartBatching":
        router = implementation["routing_class"]
        router_class = getattr(algorithms, router, None)
        if not router.isidentifier() or not inspect.isclass(router_class) or not issubclass(router_class, Routing):
            raise ValueError(f"Unknown routing_class {router!r}")
        return (header
                + "from casim.pipelines.subproblems.batching import IncumbentBatchingNode\n"
                + f"from ware_ops_algos.algorithms import {router}\n\n\n"
                + f"class {name}(IncumbentBatchingNode):\n"
                + "    abstract = False\n"
                + f"    routing_class = {router}\n")
    raise ValueError(f"No generator for {base}")


def generate_configured_components() -> dict[str, str]:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    paths = {}
    for card in load_packaged_algo_cards():
        implementation = card.implementation
        if implementation.get("class_name") not in BASES:
            continue
        name = implementation["component_name"]
        if name != card.algo_name or not name.isidentifier():
            raise ValueError(f"Configured component name does not match {card.algo_name}")
        module = _module_name(name)
        path = OUTPUT_DIR / f"{module}.py"
        if name in paths:
            raise ValueError(f"Duplicate configured component {name}")
        path.write_text(_render(name, implementation), encoding="utf-8")
        paths[name] = f"casim.pipelines.subproblems.generated.{module}.{name}"
    (OUTPUT_DIR / "__init__.py").write_text(
        '"""Generated CoSy components for configured algorithm cards."""\n',
        encoding="utf-8",
    )
    return paths


if __name__ == "__main__":
    for name, path in generate_configured_components().items():
        print(f"{name}: {path}")
